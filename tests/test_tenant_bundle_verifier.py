"""
--bundle-dir mode: POST /api/v1/checkpoints/export's tenant record bundle
(SPEC.md §13, W1-D).

Fixture lives in testdata/tenant_bundle/, regenerated by
make_tenant_bundle_fixture.py — a second implementation against SPEC.md,
same discipline as make_corpus.py/test_bundle_verifier.py. It carries two
model-version event chains (5 and 13 events — deliberately non-power-of-two,
same reasoning SPEC.md §11 gives for make_corpus.py's 5-event corpus) sealed
under one 18-leaf checkpoint and one continuity certificate.

Run:  python -m pytest tests/ -q
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import verify_proof  # noqa: E402

TESTDATA = Path(__file__).resolve().parent.parent / "testdata"
FIXTURE = TESTDATA / "tenant_bundle"


def _copy_fixture(tmp_path) -> Path:
    dest = tmp_path / "bundle"
    shutil.copytree(FIXTURE, dest)
    return dest


def test_clean_fixture_verifies_as_reduced_range(tmp_path, capsys):
    """The fixture's last beta event models a real production shape found
    against a live tenant: a seeded/legacy row whose event_hash cannot be
    re-derived under the current formula, even though its chain linkage is
    sound. Disclosed (not silently dropped, not a hard failure) — the
    verdict is the REDUCED RANGE variant, not a bare PASS."""
    bundle_dir = _copy_fixture(tmp_path)
    rc = verify_proof.run_bundle_dir(str(bundle_dir))
    out = capsys.readouterr().out
    assert rc == verify_proof.EXIT_OK
    assert "CONTINUITY VERIFIED OVER A REDUCED RANGE" in out
    assert "1 governance event(s) could not have their content re-derived" in out


def test_content_verifiable_row_that_fails_rehash_is_a_hard_fail(tmp_path, capsys):
    """The opposite of disclosure: a row the manifest marks
    content_hash_verifiable=True must still hard-fail if it does not
    actually re-hash — disclosure is only for rows honestly marked False."""
    bundle_dir = _copy_fixture(tmp_path)
    events_path = bundle_dir / "events" / "fixture-version-alpha.jsonl"
    lines = events_path.read_text().splitlines()
    row = json.loads(lines[2])
    assert row["content_hash_verifiable"] is True
    row["notes"] = "TAMPERED"
    lines[2] = json.dumps(row, separators=(",", ":"))
    new_text = "\n".join(lines) + "\n"
    events_path.write_text(new_text)

    import hashlib
    manifest_path = bundle_dir / "manifest.json"
    manifest = json.loads(manifest_path.read_text())
    manifest["files"]["events/fixture-version-alpha.jsonl"] = hashlib.sha256(
        new_text.encode("utf-8")
    ).hexdigest()
    manifest_path.write_text(json.dumps(manifest, indent=2))

    rc = verify_proof.run_bundle_dir(str(bundle_dir))
    out = capsys.readouterr().out
    assert rc == verify_proof.EXIT_TAMPER
    assert "content hash does not match" in out


def test_tampered_disclosure_count_is_caught(tmp_path, capsys):
    """manifest.json's events_not_content_verifiable_total is itself inside
    the signed-file-hash net (it's a field of manifest.json, which nothing
    hashes further up) but not cross-checked against the certificate's
    signature — so the verifier must recompute it independently from the
    events actually on disk rather than trusting the claimed count."""
    bundle_dir = _copy_fixture(tmp_path)
    manifest_path = bundle_dir / "manifest.json"
    manifest = json.loads(manifest_path.read_text())
    manifest["counts"]["events_not_content_verifiable_total"] = 0
    manifest_path.write_text(json.dumps(manifest, indent=2))

    rc = verify_proof.run_bundle_dir(str(bundle_dir))
    out = capsys.readouterr().out
    assert rc == verify_proof.EXIT_TAMPER
    assert "count itself was tampered with" in out


def test_fixture_has_non_power_of_two_event_counts():
    alpha = (FIXTURE / "events" / "fixture-version-alpha.jsonl").read_text().strip().splitlines()
    beta = (FIXTURE / "events" / "fixture-version-beta.jsonl").read_text().strip().splitlines()
    assert len(alpha) == 5
    assert len(beta) == 13
    for n in (len(alpha), len(beta), len(alpha) + len(beta)):
        assert n & (n - 1) != 0, f"{n} must not be a power of two"


def test_corrupted_event_row_fails_at_manifest_hash(tmp_path, capsys):
    """A row edited in place, manifest left untouched, is caught at the
    cheapest check (file hash), before any cryptography runs."""
    bundle_dir = _copy_fixture(tmp_path)
    events_path = bundle_dir / "events" / "fixture-version-beta.jsonl"
    lines = events_path.read_text().splitlines()
    row = json.loads(lines[5])
    row["notes"] = "TAMPERED"
    lines[5] = json.dumps(row, separators=(",", ":"))
    events_path.write_text("\n".join(lines) + "\n")

    rc = verify_proof.run_bundle_dir(str(bundle_dir))
    out = capsys.readouterr().out
    assert rc == verify_proof.EXIT_TAMPER
    assert "manifest file hashes" in out
    assert "TENANT BUNDLE VERIFICATION FAILED" in out


def test_corrupted_event_row_with_manifest_updated_fails_at_chain_check(tmp_path, capsys):
    """The harder case: the attacker also rewrites manifest.json's hash for
    the file they edited. Caught one layer deeper, by content-hash
    re-derivation and chain linkage, not by the file-hash check."""
    bundle_dir = _copy_fixture(tmp_path)
    events_path = bundle_dir / "events" / "fixture-version-beta.jsonl"
    lines = events_path.read_text().splitlines()
    row = json.loads(lines[5])
    row["notes"] = "TAMPERED-BUT-MANIFEST-UPDATED"
    lines[5] = json.dumps(row, separators=(",", ":"))
    new_text = "\n".join(lines) + "\n"
    events_path.write_text(new_text)

    import hashlib
    manifest_path = bundle_dir / "manifest.json"
    manifest = json.loads(manifest_path.read_text())
    manifest["files"]["events/fixture-version-beta.jsonl"] = hashlib.sha256(
        new_text.encode("utf-8")
    ).hexdigest()
    manifest_path.write_text(json.dumps(manifest, indent=2))

    rc = verify_proof.run_bundle_dir(str(bundle_dir))
    out = capsys.readouterr().out
    assert rc == verify_proof.EXIT_TAMPER
    assert "governance event chains link and re-hash correctly" in out
    assert "content hash does not match" in out


def test_checkpoint_removed_from_disk_but_kept_in_certificate_still_verifies(tmp_path):
    """Deleting a checkpoint file entirely (not editing it) is caught by the
    manifest file-hash check, same as any other missing file."""
    bundle_dir = _copy_fixture(tmp_path)
    for f in (bundle_dir / "checkpoints").glob("*.json"):
        f.unlink()
    rc = verify_proof.run_bundle_dir(str(bundle_dir))
    assert rc == verify_proof.EXIT_TAMPER


def test_missing_manifest_is_malformed_not_tamper(tmp_path):
    bundle_dir = _copy_fixture(tmp_path)
    (bundle_dir / "manifest.json").unlink()
    rc = verify_proof.run_bundle_dir(str(bundle_dir))
    assert rc == verify_proof.EXIT_MALFORMED


# The signed subject vs unsigned version_id rule. It used to require
# "org_default" whenever version_id was absent, which failed every honest
# bundle holding an org- or model-level package seal ("package:<id>") or an
# examiner-package seal ("examiner_package") as a subject mismatch.
def test_org_wide_subjects_other_than_org_default_are_accepted():
    for subject in ("org_default", "package:6035a961-a7e7-4189-a878-25127b443939", "examiner_package"):
        ok, _ = verify_proof.subject_matches_leaf_source(subject, None)
        assert ok, subject


def test_subject_and_version_id_must_still_agree():
    # A version subject without its version_id would read the org-wide leaves.
    assert not verify_proof.subject_matches_leaf_source("version:abc", None)[0]
    # A version_id with any other subject would read one version's leaves.
    assert not verify_proof.subject_matches_leaf_source("org_default", "abc")[0]
    assert not verify_proof.subject_matches_leaf_source("version:xyz", "abc")[0]
    assert verify_proof.subject_matches_leaf_source("version:abc", "abc")[0]
    assert not verify_proof.subject_matches_leaf_source("", None)[0]
    assert not verify_proof.subject_matches_leaf_source(None, None)[0]


def test_package_subject_must_name_the_attested_package():
    att = {"package_id": "A", "snapshot_sha256": "0" * 64,
           "package_event_hash": "1" * 64, "approval_head_hash": "2" * 64}
    assert verify_proof.package_attestation_matches_subject("package:A", att)
    assert not verify_proof.package_attestation_matches_subject("package:B", att)
    # A version-scoped package seal signs version:<id>; nothing to compare.
    assert verify_proof.package_attestation_matches_subject("version:v1", att)
    # No attestation (every non-package checkpoint, every seal made before record-wide package seals).
    assert verify_proof.package_attestation_matches_subject("package:A", None)
    assert verify_proof.package_attestation_matches_subject("org_default", None)
