def test_spliced_succession_with_no_matching_event_fails(tmp_path, capsys):
    """(b) The actual exploit: the signed succession record is genuine (real
    signature, untouched), but the matching key.succession GovernanceEvent
    is removed from events/<version_id>.jsonl — simulating a bundle spliced
    together from a genuine succession statement and a chain that never
    actually saw that handoff. MUST fail, and fail specifically on the new
    succession-binding check, not some unrelated one."""
    bundle_dir = _copy_fixture(tmp_path)
    version_id = "fixture-version-succession"
    events_path = bundle_dir / "events" / f"{version_id}.jsonl"
    rows = [json.loads(line) for line in events_path.read_text().splitlines()]

    # Drop the key.succession row and re-chain everything after it so the
    # prev_hash linkage (step 4) stays internally sound — the point is to
    # isolate the succession-binding failure, not to also trip the chain
    # linkage check with a dangling prev_hash. Re-derive event_hash for
    # every event after the removed one so step 4 (which recomputes
    # content-hash-verifiable rows independently) does not itself fail
    # first.
    kept = [r for r in rows if r["action"] != "key.succession"]
    prev = "0" * 64
    for i, row in enumerate(kept):
        row["seq"] = i
        row["ordinal"] = i
        row["prev_hash"] = prev
        row["event_hash"] = verify_proof._event_hash_of(row)
        prev = row["event_hash"]

    lines = [json.dumps(r, separators=(",", ":")) for r in kept]
    _rewrite_events_and_manifest(bundle_dir, version_id, lines)

    rc = verify_proof.run_bundle_dir(str(bundle_dir))
    out = capsys.readouterr().out
    assert rc == verify_proof.EXIT_TAMPER
    assert "TENANT BUNDLE VERIFICATION FAILED" in out
    assert "[FAIL] succession bound to chain (bundle-dir)" in out
    assert "has no matching key.succession event anywhere in" in out
    assert "exactly the splice this check exists to catch" in out


def test_matching_event_with_disagreeing_field_fails(tmp_path, capsys):
    """(c) A matching key.succession event exists (same outgoing/incoming
    key_id pair), but one field — effective_at — disagrees with the signed
    record. MUST fail, on the succession-binding check specifically."""
    bundle_dir = _copy_fixture(tmp_path)
    version_id = "fixture-version-succession"
    events_path = bundle_dir / "events" / f"{version_id}.jsonl"
    lines = events_path.read_text().splitlines()
    rows = [json.loads(line) for line in lines]

    idx = next(i for i, r in enumerate(rows) if r["action"] == "key.succession")
    notes = json.loads(rows[idx]["notes"])
    notes["effective_at"] = "2099-01-01T00:00:00+00:00"  # disagrees with the signed record
    rows[idx]["notes"] = json.dumps(notes, sort_keys=True, separators=(",", ":"))
    # event_hash is left untouched deliberately: the point of this case is
    # a chain-linked event whose CONTENT was altered post-hoc without
    # re-deriving the hash, which is caught earlier (step 4, content hash
    # mismatch) before the binding check even gets a chance to look at
    # field agreement — see the companion test below for that path. To
    # exercise the binding check itself in isolation, recompute the hash so
    # step 4 still passes and only the binding check's field-agreement
    # comparison can catch the tampering.
    rows[idx]["event_hash"] = verify_proof._event_hash_of(rows[idx])
    # Re-chain every following row so step 4's prev_hash/content-hash checks
    # still pass and only the binding check fails.
    prev = rows[idx]["event_hash"]
    for row in rows[idx + 1:]:
        row["prev_hash"] = prev
        row["event_hash"] = verify_proof._event_hash_of(row)
        prev = row["event_hash"]

    new_lines = [json.dumps(r, separators=(",", ":")) for r in rows]
    _rewrite_events_and_manifest(bundle_dir, version_id, new_lines)

    rc = verify_proof.run_bundle_dir(str(bundle_dir))
    out = capsys.readouterr().out
    assert rc == verify_proof.EXIT_TAMPER
    assert "[FAIL] succession bound to chain (bundle-dir)" in out
    assert "fields disagree with the signed record" in out
    assert "effective_at" in out


