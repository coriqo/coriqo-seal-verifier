    checkpoint_path.write_text(new_text)
    _update_manifest_hash(bundle_dir, "checkpoints/cp-succession-0001.json", new_text)

    rc = verify_proof.run_bundle_dir(str(bundle_dir))
    out = capsys.readouterr().out

    assert rc == verify_proof.EXIT_TAMPER
