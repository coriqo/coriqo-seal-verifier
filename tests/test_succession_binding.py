def _copy_fixture(tmp_path) -> Path:
    dest = tmp_path / "bundle"
    shutil.copytree(FIXTURE, dest)
    return dest


def _update_manifest_hash(bundle_dir: Path, rel_path: str, new_text: str) -> None:
    """Update manifest.json.files' recorded sha256 for one file after
    editing it in place, so the edit is caught by a deeper check
    (chain/content/root re-derivation) instead of the cheap top-level
    manifest file-hash check."""
    import hashlib

    manifest_path = bundle_dir / "manifest.json"
    manifest = json.loads(manifest_path.read_text())
    manifest["files"][rel_path] = hashlib.sha256(new_text.encode("utf-8")).hexdigest()
    manifest_path.write_text(json.dumps(manifest, indent=2))


def _fabricate_and_paste_succession(bundle_dir: Path, version_id: str) -> None:
    """The reviewer's base exploit: discard the real history, write 3
    fabricated events, paste the genuine key.succession row verbatim (only
    event_id changed), re-chain from genesis, update the manifest hash.
    Shared by both round-3 and round-4 exploit tests, which each then apply
    one additional bypass attempt on top of this base forgery."""
    events_path = bundle_dir / "events" / f"{version_id}.jsonl"
    real_rows = [json.loads(line) for line in events_path.read_text().splitlines()]
    genuine_succession_row = next(r for r in real_rows if r["action"] == "key.succession")

    fabricated = [
        {"actor": "forger", "action": "submit", "from_status": None, "to_status": "submitted",
         "notes": "fabricated event 1"},
        {"actor": "forger", "action": "assign_reviewer", "from_status": "submitted",
         "to_status": "in_review", "notes": "fabricated event 2"},
        {"actor": "forger", "action": "review", "from_status": "in_review",
         "to_status": "reviewed", "notes": "fabricated event 3"},
    ]
    forged_rows = []
    prev = "0" * 64
    for i, item in enumerate(fabricated):
        row = {
            "event_id": f"forged-ev{i}", "version_id": version_id, "ordinal": i, "seq": i,
            "actor": item["actor"], "actor_type": "human", "action": item["action"],
            "from_status": item["from_status"], "to_status": item["to_status"],
            "notes": item["notes"], "prev_hash": prev, "content_hash_verifiable": True,
            "oversight": None, "created_at": "2026-09-08T00:00:00+00:00",
        }
        row["event_hash"] = verify_proof._event_hash_of(row)
        forged_rows.append(row)
        prev = row["event_hash"]

    pasted = dict(genuine_succession_row)
    pasted["event_id"] = "forged-succession-ev"
    pasted["ordinal"] = len(forged_rows)
    pasted["seq"] = len(forged_rows)
    pasted["prev_hash"] = prev
    pasted["event_hash"] = verify_proof._event_hash_of(pasted)
    forged_rows.append(pasted)

    lines = [json.dumps(r, separators=(",", ":")) for r in forged_rows]
    new_text = "\n".join(lines) + "\n"
    events_path.write_text(new_text)
    _update_manifest_hash(bundle_dir, f"events/{version_id}.jsonl", new_text)


def _rewrite_events_and_manifest(bundle_dir: Path, version_id: str, lines: list[str]) -> None:
    """Write back events/<version_id>.jsonl and update manifest.json.files'
    hash for it, so the change is caught by step 4 (chain re-derivation),
    not by the earlier, cheaper manifest file-hash check — the same
    pattern test_tenant_bundle_verifier.py's
    ...with_manifest_updated_fails_at_chain_check uses."""
    import hashlib

    events_path = bundle_dir / "events" / f"{version_id}.jsonl"
    new_text = "\n".join(lines) + "\n"
    events_path.write_text(new_text)
    manifest_path = bundle_dir / "manifest.json"
    manifest = json.loads(manifest_path.read_text())
    manifest["files"][f"events/{version_id}.jsonl"] = hashlib.sha256(
        new_text.encode("utf-8")
    ).hexdigest()
    manifest_path.write_text(json.dumps(manifest, indent=2))


