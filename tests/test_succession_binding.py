def test_chain_guard_round4_critical2_content_hash_flag_no_longer_bypasses_binding(
    tmp_path, capsys,
):
    """
    Round-4 chain-guard finding, CRITICAL 2: step 4's own content-hash
    re-derivation is gated by each row's (forger-controlled)
    `content_hash_verifiable` flag, and round-3's succession-binding check
    only compared PARSED fields (dict equality — representation-blind) —
    it never independently re-hashed the matched row's own RAW bytes. The
    reviewer kept every genuine event_hash/prev_hash/ordinal untouched (so
    the Merkle root still recomputes identically, and the parsed succession
    fields still dict-equal the certificate's genuine signed record) but
    rewrote the byte-level representation of the succession event's `notes`
    string (re-serialized, different whitespace/key order — parses back to
    the identical field values) and set content_hash_verifiable: false,
    specifically to dodge step 4's flag-gated check. The stored event_hash
    (untouched) was computed over the ORIGINAL notes bytes, not these new
    ones. Root check passes (leaves untouched), succession-binding's old
    field-comparison-only logic passes (dict equality does not see the
    byte-level change), verdict would have come back CONTINUITY VERIFIED
    OVER A REDUCED RANGE.

    MUST fail now: succession-binding must unconditionally recompute the
    matched row's own event_hash from its current (raw) content, regardless
    of content_hash_verifiable, and reject a mismatch.
    """
    bundle_dir = _copy_fixture(tmp_path)
    version_id = "fixture-version-succession"
    events_path = bundle_dir / "events" / f"{version_id}.jsonl"
    rows = [json.loads(line) for line in events_path.read_text().splitlines()]

    idx = next(i for i, r in enumerate(rows) if r["action"] == "key.succession")
    # Stored event_hash and prev_hash are left EXACTLY as they were — the
    # whole point of this bypass attempt is that nothing the Merkle-root
    # check, the chain-linkage check, or a naive field-by-field dict
    # comparison would notice. Only the exact BYTES of `notes` change —
    # re-serialized with different formatting, same field values — plus
    # the flag that would otherwise make step 4 catch it.
    original_notes_fields = json.loads(rows[idx]["notes"])
    rows[idx]["notes"] = json.dumps(original_notes_fields, indent=2)  # same fields, different bytes
    rows[idx]["content_hash_verifiable"] = False
    # event_hash and prev_hash: UNTOUCHED — still the genuine, original
    # values, computed over the ORIGINAL (compact) notes bytes.

    new_text = "\n".join(json.dumps(r, separators=(",", ":")) for r in rows) + "\n"
    events_path.write_text(new_text)
    _update_manifest_hash(bundle_dir, f"events/{version_id}.jsonl", new_text)
    # events_not_content_verifiable_total must also be bumped by 1, or step 4
    # catches this as a tampered-count mismatch instead of the check this
    # test targets — the point is to isolate the succession-binding fix,
    # not to also trip a different, already-covered check.
    manifest_path = bundle_dir / "manifest.json"
    manifest = json.loads(manifest_path.read_text())
    manifest["counts"]["events_not_content_verifiable_total"] = 1
    manifest_path.write_text(json.dumps(manifest, indent=2))

    rc = verify_proof.run_bundle_dir(str(bundle_dir))
    out = capsys.readouterr().out

    assert rc == verify_proof.EXIT_TAMPER
    assert "TENANT BUNDLE VERIFICATION FAILED" in out
    # Must fail specifically on succession-binding's own content
    # re-derivation, not on step 4 (which the content_hash_verifiable:false
    # flag deliberately disarms for this row) and not on the Merkle-root
    # check (leaves are untouched, so it still passes).
    assert "[PASS] checkpoint Merkle roots recompute from events/*.jsonl leaves" in out
    assert "[FAIL] succession bound to chain (bundle-dir)" in out
    assert "does NOT match a fresh hash of its own content" in out
    assert "content_hash_verifiable is ignored here on purpose" in out


def test_checkpoint_subject_version_id_mismatch_fails_loudly(tmp_path, capsys):
    """
    Defense in depth (merge-gate follow-up): `version_id` picks which
    events/*.jsonl file a checkpoint's leaves are read from, but
    version_id is not itself covered by the checkpoint's Ed25519
    signature (only subject/issued_at/length/head_hash/merkle_root/
    tree_size/key_id are). A checkpoint file edited so its (unsigned)
    version_id no longer names the same chain its SIGNED subject does
    must fail loudly rather than silently read the wrong leaf source.
    """
    bundle_dir = _copy_fixture(tmp_path)
    checkpoint_path = bundle_dir / "checkpoints" / "cp-succession-0001.json"
    checkpoint = json.loads(checkpoint_path.read_text())
    assert checkpoint["subject"] == "version:fixture-version-succession"
    checkpoint["version_id"] = "some-other-version-entirely"
    new_text = json.dumps(checkpoint, indent=2)
    checkpoint_path.write_text(new_text)
    _update_manifest_hash(bundle_dir, "checkpoints/cp-succession-0001.json", new_text)

    rc = verify_proof.run_bundle_dir(str(bundle_dir))
    out = capsys.readouterr().out

    assert rc == verify_proof.EXIT_TAMPER
    assert "[FAIL] checkpoint Merkle roots recompute from events/*.jsonl leaves" in out
    assert "SIGNED subject" in out
    assert "does not match its own version_id field" in out


